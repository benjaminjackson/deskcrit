// EV-1, the durable golden-output test for `crit report`, `crit compare`, and `crit gate` (CS-21, AC-6). Each folder under
// evals/golden/cases/ names the arguments in case.json and stores the stdout, stderr, and exit code
// a person approved. The test runs the built bundle twice per case with a recorded --answers file
// and an environment that holds only PATH, so it makes no network call and needs no key (FR-42).
// It imports nothing from src/, so a rewrite of crit in another language must still pass it.
//
// Inputs: evals/golden/images/page.png is a copy of packs/_example/fixtures/example-contrast.positive.png
// (own work, MIT, see packs/_example/fixtures/ATTRIBUTION.md). evals/golden/images/too-tall.png is
// a plain white 320 x 4000 PNG made once with sharp. evals/golden/images/page-large.png is page.png
// resized to 2000 x 1250 with sharp, so prepare scales it by 0.784. evals/golden/answers/page.answers.json
// and evals/golden/answers/page-large.answers.json were recorded once from Jev with --save-answers
// on 2026-10-24 and are not regenerated by the tests. Their image_sha256 keys were added later
// from the image files, with no new call (OQ-26 e). evals/golden/answers/too-tall.answers.json is
// page.answers.json with the fingerprint of too-tall.png, so the image-too-tall case reaches prepare.
// The gate cases use evals/golden/answers/gate-pass.answers.json, gate-warn.answers.json, and
// gate-uncertain.answers.json, which keep only the answers of page.answers.json that their packs in
// evals/golden/packs/gate-*/ ask, with the same image_sha256 and usage. Two gate cases run from
// evals/golden/warn-fails-gate/, whose .crit.yaml sets warn_fails_gate: true.
// The compare cases use evals/golden/answers/compare-*.answers.json, two-run files (version 2) that
// were written by hand for the pack in evals/golden/packs/compare/, not recorded from Jev. Each run
// copies its image_sha256 and usage from page.answers.json (before) or page-large.answers.json
// (after; both runs in compare-same-image), and its distributions were chosen to give each change
// of FR-36 and FR-37. These cases check the CLI, not Jev.

import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  GOLDEN_DIRECTORY,
  isJsonCase,
  normaliseReportJson,
  readExpectedOutput,
  readGoldenCases,
  runCrit,
} from "./support/run-crit.js";

/** The verdict order of PRD FR-28: fail, then warn, uncertain, and pass. */
const VERDICT_ORDER = ["fail", "warn", "uncertain", "pass"];

/** The fields every finding has (FR-26). */
const FINDING_FIELDS = [
  "criterion",
  "title",
  "verdict",
  "distribution",
  "confidence",
  "region",
  "source",
  "link",
  "fix",
  "model",
];

/** The fields of usage (FR-33). */
const USAGE_FIELDS = ["requests", "input_tokens", "cost_usd", "latency_ms"];

const goldenCases = readGoldenCases();

/** Return the golden case with this folder name, or throw so a renamed case cannot pass silently. */
function findGoldenCase(name: string) {
  for (const goldenCase of goldenCases) {
    if (goldenCase.name === name) {
      return goldenCase;
    }
  }
  throw new Error(`No golden case named ${name}`);
}

/** Return true when the case runs `crit gate`, whose exit code 1 means the gate failed (FR-40). */
function isGateCase(goldenCase: {
  readonly arguments: readonly string[];
}): boolean {
  return goldenCase.arguments[0] === "gate";
}

/** Return the keys of a JSON object in sorted order, so a test can compare key sets. */
function sortedKeysOf(value: object): string[] {
  const keys = Object.keys(value);
  keys.sort();
  return keys;
}

// Each case runs the bundle twice as a child process. Under load, such as several test runs at once,
// that takes longer than the Vitest default of 5 seconds, so the case gets more time. Nothing it checks changes.
const CRIT_TWICE_TIMEOUT_MS = 30_000;

describe("EV-1: golden outputs of crit report", () => {
  it("has golden cases to run", () => {
    expect(goldenCases.length).toBeGreaterThan(0);
  });

  for (const goldenCase of goldenCases) {
    it(
      `${goldenCase.name}: ${goldenCase.description}`,
      () => {
        const expected = readExpectedOutput(goldenCase);
        const firstRun = runCrit(
          goldenCase.arguments,
          goldenCase.workingDirectory,
        );
        const secondRun = runCrit(
          goldenCase.arguments,
          goldenCase.workingDirectory,
        );

        // Two runs of the same case give the same bytes, so a hidden nondeterminism shows up (NFR-5).
        expect(secondRun).toEqual(firstRun);

        expect(firstRun.exitCode).toBe(expected.exitCode);
        expect(firstRun.stderr).toBe(expected.stderr);
        if (isGateCase(goldenCase)) {
          // crit gate writes its document on exit 0 and exit 1, and nothing on exit 2 (FR-24, FR-40, FR-61).
          if (firstRun.exitCode === 2) {
            expect(firstRun.stdout).toBe("");
          }
        } else if (firstRun.exitCode !== 0) {
          // A run that could not run writes nothing to stdout (FR-24, FR-61).
          expect(firstRun.stdout).toBe("");
        }
        if (isJsonCase(goldenCase) && expected.stdout !== "") {
          // JSON.parse of the whole stdout fails unless it holds exactly one JSON document (FR-31, FR-61).
          expect(normaliseReportJson(firstRun.stdout)).toBe(
            normaliseReportJson(expected.stdout),
          );
        } else {
          expect(firstRun.stdout).toBe(expected.stdout);
        }
      },
      CRIT_TWICE_TIMEOUT_MS,
    );
  }
});

describe("EV-1: what the report-json golden case shows", () => {
  const goldenCase = findGoldenCase("report-json");
  const result = runCrit(goldenCase.arguments);
  const report = JSON.parse(result.stdout);

  it("exits 0 with a fail finding, with no TYPESAFE_API_KEY in the environment (FR-42, FR-43)", () => {
    expect(result.exitCode).toBe(0);
    expect(result.stderr).toBe("");
    const verdicts: string[] = [];
    for (const finding of report.findings) {
      verdicts.push(finding.verdict);
    }
    expect(verdicts).toContain("fail");
  });

  it("has every finding field and a fail, warn, uncertain, and pass finding in FR-28 order (FR-26, FR-28)", () => {
    const verdicts: string[] = [];
    for (const finding of report.findings) {
      expect(sortedKeysOf(finding)).toEqual([...FINDING_FIELDS].sort());
      verdicts.push(finding.verdict);
    }
    for (const verdict of VERDICT_ORDER) {
      expect(verdicts).toContain(verdict);
    }
    for (let index = 1; index < verdicts.length; index++) {
      const previousRank = VERDICT_ORDER.indexOf(verdicts[index - 1] ?? "");
      const currentRank = VERDICT_ORDER.indexOf(verdicts[index] ?? "");
      expect(currentRank).toBeGreaterThanOrEqual(previousRank);
    }
  });

  it("gives the located finding that did not pass a region inside the original image (US-1)", () => {
    let locatedFindings = 0;
    for (const finding of report.findings) {
      if (finding.region === null) {
        continue;
      }
      locatedFindings += 1;
      expect(finding.verdict).not.toBe("pass");
      expect(finding.region.x).toBeGreaterThanOrEqual(0);
      expect(finding.region.y).toBeGreaterThanOrEqual(0);
      expect(finding.region.x + finding.region.width).toBeLessThanOrEqual(
        report.image.width,
      );
      expect(finding.region.y + finding.region.height).toBeLessThanOrEqual(
        report.image.height,
      );
    }
    expect(locatedFindings).toBe(1);
  });

  it("lists skipped criteria with a reason, sorted by criterion, and the missing fact path (FR-13, US-9)", () => {
    const criteria: string[] = [];
    for (const skipped of report.skipped) {
      expect(sortedKeysOf(skipped)).toEqual(["criterion", "reason"]);
      criteria.push(skipped.criterion);
    }
    const sortedCriteria = [...criteria];
    sortedCriteria.sort();
    expect(criteria).toEqual(sortedCriteria);
    expect(report.skipped).toContainEqual({
      criterion: "golden/content-fills-viewport",
      reason:
        "requires facts.viewport_width, which the facts file does not have",
    });
  });

  it("keeps usage to its four fields and puts the model at the top level and on each finding (FR-33)", () => {
    expect(sortedKeysOf(report.usage)).toEqual([...USAGE_FIELDS].sort());
    expect(typeof report.model).toBe("string");
    for (const finding of report.findings) {
      expect(finding.model).toBe(report.model);
    }
  });

  it("records the answers as the file gave them, so the recorded usage reaches the report (FR-42)", () => {
    const answersFile = JSON.parse(
      readFileSync(
        join(GOLDEN_DIRECTORY, "answers", "page.answers.json"),
        "utf8",
      ),
    );
    expect(report.usage.input_tokens).toBe(answersFile.usage.input_tokens);
    expect(report.usage.cost_usd).toBe(answersFile.usage.cost_usd);
  });
});

describe("EV-1: what the report-text golden case shows", () => {
  const goldenCase = findGoldenCase("report-text");
  const result = runCrit(goldenCase.arguments);

  it("groups findings by verdict in FR-28 order and ends with the usage line (FR-32, FR-33)", () => {
    expect(result.exitCode).toBe(0);
    const failIndex = result.stdout.indexOf("Fail (");
    const warnIndex = result.stdout.indexOf("Warn (");
    const uncertainIndex = result.stdout.indexOf("Uncertain (");
    const passIndex = result.stdout.indexOf("Pass (");
    expect(failIndex).toBe(0);
    expect(warnIndex).toBeGreaterThan(failIndex);
    expect(uncertainIndex).toBeGreaterThan(warnIndex);
    expect(passIndex).toBeGreaterThan(uncertainIndex);
    const lines = result.stdout.trimEnd().split("\n");
    const lastLine = lines[lines.length - 1] ?? "";
    expect(lastLine).toMatch(/^Requests: 1, input tokens: \d+, cost: \$/);
    expect(lastLine).toContain("model: jev-");
  });

  it("writes no colour codes when stdout is not a terminal (FR-32)", () => {
    // \u001b is the escape character that starts every terminal colour code.
    expect(result.stdout).not.toContain("\u001b");
  });
});

describe("EV-1: what the crit gate golden cases show (FR-40, FR-41, section 8.3)", () => {
  /** The gate --json cases that ran, so their stdout is one gate document. */
  const gateJsonCases = goldenCases.filter((goldenCase) => {
    if (!isGateCase(goldenCase) || !isJsonCase(goldenCase)) {
      return false;
    }
    return readExpectedOutput(goldenCase).exitCode !== 2;
  });

  it("has gate cases that pass and that fail", () => {
    const exitCodes = new Set<number>();
    for (const goldenCase of gateJsonCases) {
      exitCodes.add(readExpectedOutput(goldenCase).exitCode);
    }
    expect([...exitCodes].sort()).toEqual([0, 1]);
  });

  for (const goldenCase of gateJsonCases) {
    it(`${goldenCase.name}: the exit code agrees with gate.passed, and the policy is the one the case set`, () => {
      const result = runCrit(goldenCase.arguments, goldenCase.workingDirectory);
      const document = JSON.parse(result.stdout);
      expect(document.mode).toBe("gate");
      let expectedExitCode = 1;
      if (document.gate.passed) {
        expectedExitCode = 0;
      }
      expect(result.exitCode).toBe(expectedExitCode);
      // Only the cases that run from evals/golden/warn-fails-gate/ read a .crit.yaml that sets the policy.
      const policyOn = goldenCase.workingDirectory.endsWith("warn-fails-gate");
      expect(document.gate.policy).toEqual({ warn_fails_gate: policyOn });
      // A gate passes exactly when nothing blocks it (section 8.3).
      expect(document.gate.passed).toBe(document.gate.blocking.length === 0);
      // Uncertain and pass findings never block (FR-40, FR-41, US-9).
      for (const finding of document.findings) {
        if (finding.verdict === "uncertain" || finding.verdict === "pass") {
          expect(document.gate.blocking).not.toContain(finding.criterion);
        }
      }
    });
  }
});

/** The four values of a compare change, in the order of the readable compare output (FR-36, FR-37). */
const CHANGE_VALUES = ["worse", "better", "uncertain", "same"];

/** Return true when the case runs `crit compare` (FR-60). */
function isCompareCase(goldenCase: {
  readonly arguments: readonly string[];
}): boolean {
  return goldenCase.arguments[0] === "compare";
}

/** Return true when the list of entries is sorted by criterion, by UTF-16 code unit (section 8.2). */
function isSortedByCriterion(
  entries: readonly { readonly criterion: string }[],
): boolean {
  for (let index = 1; index < entries.length; index++) {
    const previous = entries[index - 1];
    const current = entries[index];
    if (previous !== undefined && current !== undefined) {
      if (previous.criterion > current.criterion) {
        return false;
      }
    }
  }
  return true;
}

/** Read one answers file as JSON, from its path relative to evals/golden/ as case.json gives it. */
function readGoldenAnswersFile(relativePath: string) {
  return JSON.parse(readFileSync(join(GOLDEN_DIRECTORY, relativePath), "utf8"));
}

describe("EV-1: what the crit compare golden cases show (FR-35 to FR-37, FR-39, FR-43, section 8.2)", () => {
  /** The compare --json cases that ran, so their stdout is one compare document. */
  const compareJsonCases = goldenCases.filter((goldenCase) => {
    if (!isCompareCase(goldenCase) || !isJsonCase(goldenCase)) {
      return false;
    }
    return readExpectedOutput(goldenCase).exitCode === 0;
  });

  it("has compare cases that between them show every change value (FR-36, FR-37)", () => {
    const changesSeen = new Set<string>();
    for (const goldenCase of compareJsonCases) {
      const document = JSON.parse(runCrit(goldenCase.arguments).stdout);
      for (const entry of document.changes) {
        changesSeen.add(entry.change);
      }
    }
    expect([...changesSeen].sort()).toEqual([...CHANGE_VALUES].sort());
  });

  for (const goldenCase of compareJsonCases) {
    it(`${goldenCase.name}: the document has mode compare, a summary that counts the changes, sorted lists, and summed usage`, () => {
      const result = runCrit(goldenCase.arguments);
      expect(result.exitCode).toBe(0);
      expect(result.stderr).toBe("");
      const document = JSON.parse(result.stdout);
      expect(document.mode).toBe("compare");

      const tally = { improved: 0, regressed: 0, same: 0, uncertain: 0 };
      for (const entry of document.changes) {
        expect(CHANGE_VALUES).toContain(entry.change);
        // The model id is on each change and at the top level, and not in usage (FR-33).
        expect(entry.model).toBe(document.model);
        if (entry.change === "better") {
          tally.improved += 1;
        } else if (entry.change === "worse") {
          tally.regressed += 1;
        } else if (entry.change === "same") {
          tally.same += 1;
        } else {
          tally.uncertain += 1;
        }
      }
      expect(document.summary).toEqual(tally);
      expect(isSortedByCriterion(document.changes)).toBe(true);
      expect(isSortedByCriterion(document.skipped)).toBe(true);
      // Both runs share packs, context, and facts (FR-35), so build skips the same criteria in
      // both and crit compare always writes an empty skipped list. The PRD records this at FR-36.
      expect(document.skipped).toEqual([]);
      expect(document.before.skipped).toEqual(document.after.skipped);

      // usage holds the sums over both runs: one request each, and the recorded token counts and costs (FR-33).
      expect(sortedKeysOf(document.usage)).toEqual([...USAGE_FIELDS].sort());
      expect(document.usage.requests).toBe(2);
      const answersPath =
        goldenCase.arguments[goldenCase.arguments.indexOf("--answers") + 1] ??
        "";
      const answersFile = readGoldenAnswersFile(answersPath);
      expect(document.usage.input_tokens).toBe(
        answersFile.before.usage.input_tokens +
          answersFile.after.usage.input_tokens,
      );
      expect(document.usage.cost_usd).toBe(
        answersFile.before.usage.cost_usd + answersFile.after.usage.cost_usd,
      );
      expect(document.usage.latency_ms).toBe(
        answersFile.before.usage.latency_ms +
          answersFile.after.usage.latency_ms,
      );
    });
  }

  it("compare-better-json: single-focal-point moves from level 2 to level 0, so its change is better (US-3)", () => {
    const goldenCase = findGoldenCase("compare-better-json");
    const document = JSON.parse(runCrit(goldenCase.arguments).stdout);
    let found = 0;
    for (const entry of document.changes) {
      if (entry.criterion !== "compare/single-focal-point") {
        continue;
      }
      found += 1;
      expect(entry.change).toBe("better");
      expect(entry.before).toEqual({ verdict: "fail", value: 2 });
      expect(entry.after).toEqual({ verdict: "pass", value: 0 });
    }
    expect(found).toBe(1);
  });

  it("compare-worse-json: every change is worse and crit compare still exits 0 (FR-43)", () => {
    const goldenCase = findGoldenCase("compare-worse-json");
    const result = runCrit(goldenCase.arguments);
    expect(result.exitCode).toBe(0);
    const document = JSON.parse(result.stdout);
    expect(document.changes.length).toBeGreaterThan(0);
    for (const entry of document.changes) {
      expect(entry.change).toBe("worse");
    }
  });

  it("compare-text: groups the changes worse, better, uncertain, same, then the summary and the usage line (FR-32, FR-33, FR-39)", () => {
    const goldenCase = findGoldenCase("compare-text");
    const result = runCrit(goldenCase.arguments);
    expect(result.exitCode).toBe(0);
    const worseIndex = result.stdout.indexOf("Worse (");
    const betterIndex = result.stdout.indexOf("Better (");
    const uncertainIndex = result.stdout.indexOf("Uncertain (");
    const sameIndex = result.stdout.indexOf("Same (");
    expect(worseIndex).toBe(0);
    expect(betterIndex).toBeGreaterThan(worseIndex);
    expect(uncertainIndex).toBeGreaterThan(betterIndex);
    expect(sameIndex).toBeGreaterThan(uncertainIndex);
    const lines = result.stdout.trimEnd().split("\n");
    expect(lines[lines.length - 2]).toBe(
      "Improved: 1, regressed: 1, same: 1, uncertain: 1",
    );
    expect(lines[lines.length - 1]).toMatch(
      /^Requests: 2, input tokens: \d+, cost: \$/,
    );
    // \u001b is the escape character that starts every terminal colour code.
    expect(result.stdout).not.toContain("\u001b");
  });

  it(
    "--save-answers on a replay writes the same two-run file, and a replay of that file gives the same output (FR-42)",
    () => {
      const goldenCase = findGoldenCase("compare-better-json");
      const temporaryDirectory = mkdtempSync(join(tmpdir(), "crit-compare-"));
      try {
        const savedPath = join(temporaryDirectory, "saved.answers.json");
        const firstRun = runCrit([
          ...goldenCase.arguments,
          "--save-answers",
          savedPath,
        ]);
        expect(firstRun.stderr).toBe("");
        expect(firstRun.exitCode).toBe(0);
        const savedText = readFileSync(savedPath, "utf8");
        const originalText = readFileSync(
          join(GOLDEN_DIRECTORY, "answers", "compare-mixed.answers.json"),
          "utf8",
        );
        expect(savedText).toBe(originalText);

        const replayArguments = [...goldenCase.arguments];
        replayArguments[replayArguments.indexOf("--answers") + 1] = savedPath;
        const replay = runCrit(replayArguments);
        expect(replay.exitCode).toBe(0);
        expect(replay.stdout).toBe(firstRun.stdout);
      } finally {
        // recursive and force remove the folder and the file in it, and do not fail if it is gone.
        rmSync(temporaryDirectory, { recursive: true, force: true });
      }
    },
    CRIT_TWICE_TIMEOUT_MS,
  );
});
